"""
Shared Pydantic schemas for SpecGuard.

These schemas define the contract between Person A (AI layer) and Person B (Platform layer).
Do not change these without explicit agreement from both sides.
"""

from pydantic import BaseModel
from typing import Literal, Optional
from datetime import datetime


class Requirement(BaseModel):
    """Represents a single requirement extracted from the specification."""
    id: str
    text: str
    category: Literal["functional", "performance", "security", "data"]
    measurable_criteria: str
    ambiguous: bool = False
    clarification_note: Optional[str] = None


class GeneratedTest(BaseModel):
    """Represents a test generated by the AI layer."""
    id: str
    requirement_id: str
    pytest_code: str
    description: str


class StaticFinding(BaseModel):
    """Represents a static analysis finding from AST inspection."""
    requirement_id: str
    line: int
    message: str


class TestResult(BaseModel):
    """Represents the result of executing a single test."""
    test_id: str
    requirement_id: str
    status: Literal["passed", "failed", "error", "timeout", "flaky"]
    output: str
    duration_ms: int


class FixSuggestion(BaseModel):
    """Represents a suggested fix for a failing requirement."""
    requirement_id: str
    explanation: str
    patched_code: str
